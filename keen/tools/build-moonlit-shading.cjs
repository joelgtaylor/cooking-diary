// Bake only opaque masonry shading; source art, tile phase and alpha stay intact.
const fs=require('node:fs'),path=require('node:path');
const {createCanvas,loadImage}=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES+'/@napi-rs/canvas');
const root=path.resolve(__dirname,'..');
(async()=>{
 const terrain=await loadImage(path.join(root,'art/moonlit-terrain.png'));
 const brightness=[.92,.9,.55,.48,.58,.95,.5,.65,.8];
 const tiles=createCanvas(256,96),ctx=tiles.getContext('2d');ctx.imageSmoothingEnabled=false;
 brightness.forEach((b,i)=>{ctx.clearRect(0,0,256,96);ctx.filter='brightness('+b+')';ctx.drawImage(terrain,0,0);fs.writeFileSync(path.join(root,'art/moonlit-shade-'+i+'.png'),tiles.toBuffer('image/png'));});
 fs.writeFileSync(path.join(root,'art/moonlit-shading.js'),'/* Generated by tools/build-moonlit-shading.cjs. */\nwindow.CrustMoonlitShading='+JSON.stringify({terrainBrightness:brightness})+';\n');
})();
